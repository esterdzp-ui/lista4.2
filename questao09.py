# EXERCÍCIO 9: Teste de Maioridade
# Enunciado: Crie um script que peça a idade do usuário. Se for 18 ou mais, exiba "Acesso Liberado ao Jogo". Caso contrário, exiba "Acesso Negado".

# ENTRADA
idade = int(input("Digite sua idade: "))

# PROCESSAMENTO + SAÍDA
if idade >= 18:
    print("Acesso Liberado ao Jogo")
else:
    print("Acesso Negado")
