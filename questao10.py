# EXERCÍCIO 10: Par ou Ímpar
# Enunciado: Peça um número ao usuário. Use o operador % e uma estrutura if/else para dizer se o número é par ou ímpar.

# ENTRADA
numero = int(input("Digite um número: "))

# PROCESSAMENTO + SAÍDA
if numero % 2 == 0:
    print("O número é par")
else:
    print("O número é ímpar")
